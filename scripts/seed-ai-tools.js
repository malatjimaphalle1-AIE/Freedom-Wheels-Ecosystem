async function main() {
  console.log('[seed-ai-tools] Starting...')

  let created = 0
  let updated = 0

  for (const tool of AI_TOOLS) {
    const existing = await db.aiTool.findUnique({ where: { name: tool.name } })

    if (existing) {
      await db.aiTool.update({
        where: { id: existing.id },
        data: tool,
      })
      updated++
    } else {
      await db.aiTool.create({ data: tool })
      created++
    }
    console.log(`[seed-ai-tools] ✓ ${tool.name}`)
  }

  const total = await db.aiTool.count()
  console.log(`[seed-ai-tools] Done. ${created} created, ${updated} updated. ${total} tools total.`)
}

main()
  .catch((err) => {
    console.error('[seed-ai-tools] FATAL:', err)
    process.exit(0) // don't fail the build
  })
  .finally(async () => {
    await db.$disconnect()
  })
